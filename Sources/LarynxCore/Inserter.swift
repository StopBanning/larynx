import AppKit
import LarynxText
import ApplicationServices
import Carbon.HIToolbox

/// Puts text into whatever app has focus: clipboard plus a synthetic Cmd+V, then the old clipboard comes back.
public enum Inserter {
    /// True once the user has allowed this app in System Settings > Privacy & Security > Accessibility.
    public static var isTrusted: Bool { AXIsProcessTrusted() }

    /// Shows macOS's own Accessibility prompt. The user flips the switch; we never do.
    public static func requestTrust() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    /// Password fields turn on Secure Input, which blocks synthetic keystrokes.
    public static var secureInputActive: Bool { IsSecureEventInputEnabled() }

    public static func paste(_ text: String, restoreAfter delay: TimeInterval = 0.5, restore: Bool = true) throws {
        guard !text.isEmpty else { return }
        guard isTrusted else { throw LarynxError.notTrusted }
        guard !secureInputActive else { throw LarynxError.secureInput }

        let board = NSPasteboard.general
        let saved: [[(NSPasteboard.PasteboardType, Data)]] = (board.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
        writeTransient(text, to: board)
        let ourChange = board.changeCount

        if ProcessInfo.processInfo.environment["LARYNX_TEST_DROP_PASTE"] != "1" { sendCommandV() }  // tests: a paste that never arrives
        guard restore else { return }

        DispatchQueue.main.asyncAfter(deadline: .now() + delay) {
            // Leave the clipboard alone if the user copied something new meanwhile.
            guard board.changeCount == ourChange else { return }
            board.clearContents()
            let items = saved.map { pairs -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in pairs { item.setData(data, forType: type) }
                return item
            }
            if !items.isEmpty { board.writeObjects(items) }
        }
    }

    /// The clipboard for a paste: marked transient and auto-generated (the nspasteboard.org convention), so clipboard
    /// managers don't record every dictation. The "copied, press ⌘V" fallback is written normally instead.
    public static let transientTypes = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                                        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]
    public static func writeTransient(_ text: String, to board: NSPasteboard) {
        board.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in transientTypes { item.setData(Data(), forType: type) }
        board.writeObjects([item])
    }

    /// Puts text on the clipboard and leaves it there, for when pasting is impossible. The transcript is never lost.
    public static func copyOnly(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
    }

    public enum Delivery: Sendable, Equatable {
        case inserted
        case copied(String)  // why the paste didn't happen
        case pastedAndCopied(String)  // pasted, but it's unclear a text field took it, so it's also on the clipboard
        case insertedBy(String)  // the paste didn't arrive; inserted another way ("accessibility", "typing")

        /// The words are in the field (pasted, or inserted another way).
        public var isInserted: Bool {
            switch self { case .inserted, .insertedBy: return true; default: return false }
        }

        public var label: String {
            switch self {
            case .inserted: return "inserted"
            case .copied: return "copied"
            case .pastedAndCopied: return "pasted+copied"
            case .insertedBy(let how): return "inserted by " + how
            }
        }
    }

    /// Pastes into `target` (the app that was in front when the user started talking), bringing it back to the front
    /// first if they switched away. Anything that stops the paste falls back to leaving the text on the clipboard.
    /// `LARYNX_FORCE_COPY=1` forces the fallback, for testing.
    @MainActor
    public static func deliver(_ text: String, to target: NSRunningApplication? = nil,
                               keepsCapital: ((String) -> Bool)? = nil) async -> Delivery {
        var text = text
        if ProcessInfo.processInfo.environment["LARYNX_FORCE_COPY"] == "1" {
            copyOnly(text); return .copied("LARYNX_FORCE_COPY is set")
        }
        if let target, NSWorkspace.shared.frontmostApplication?.processIdentifier != target.processIdentifier {
            guard !target.isTerminated else { copyOnly(text); return .copied("the app you started in has quit") }
            target.activate()
            for _ in 0..<6 where NSWorkspace.shared.frontmostApplication?.processIdentifier != target.processIdentifier {
                try? await Task.sleep(nanoseconds: 50_000_000)
            }
            guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier else {
                copyOnly(text); return .copied("could not bring \(target.localizedName ?? "the app") back to the front")
            }
            try? await Task.sleep(nanoseconds: 80_000_000)  // let its window take key focus
        }
        let focus = focusedField(in: target ?? NSWorkspace.shared.frontmostApplication)
        guard focus.editable != false else {
            // Nothing to type into: pressing ⌘V would lose the words, so leave them on the clipboard.
            copyOnly(text); return .copied("no text field has focus (\(focus.role))")
        }
        // Where the field's text can be read, note it now so we can tell whether the paste arrived.
        let element = focus.editable == true ? focusedElement(in: target ?? NSWorkspace.shared.frontmostApplication) : nil
        let before = element.flatMap(value(of:))
        // Fit the words to what's already there: a missing space, or a capital that only meant "new sentence".
        if let keepsCapital, let element, Settings.shared.string(.fitToField) != "off", let cursor = textBeforeCursor(element) {
            text = Fit.adjust(text, before: cursor.before, replacingSelection: cursor.selected > 0,
                              keepsCapital: keepsCapital, isEnglish: { Vocabulary.isEnglish($0) })
        }
        do {
            // When macOS can't say whether a text field has focus, paste anyway but keep the words on the clipboard.
            try paste(text, restore: focus.editable == true)
        }
        catch { copyOnly(text); return .copied("\(error)") }
        guard focus.editable == true else { return .pastedAndCopied(focus.role) }
        guard let element, let before, Settings.shared.string(.verifyPaste) != "off" else { return .inserted }
        // Only a field that is readable, still the same field, and still exactly the same text after 0.6 s counts as
        // a paste that didn't arrive. Anything else (it changed, can't be read, or the app replaced the field, as
        // Claude does right after a message is sent) is left alone, so text is never inserted twice.
        let app = target ?? NSWorkspace.shared.frontmostApplication
        switch await outcome(element, in: app, from: before, within: 0.6) {
        case .changed: return .inserted
        // Can't tell (the app replaced the field, or it can't be read): never paste again, but leave the words on
        // the clipboard too, so a paste that missed is one ⌘V away instead of gone.
        case .unknown: copyOnly(text); return .pastedAndCopied("couldn't confirm the paste")
        case .unchanged: break
        }
        if AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success {
            switch await outcome(element, in: app, from: before, within: 0.3) {
            case .changed: return .insertedBy("accessibility")
            case .unknown: copyOnly(text); return .pastedAndCopied("couldn't confirm the insert")
            case .unchanged: break
            }
        }
        if case .unchanged = await outcome(element, in: app, from: before, within: 0) {
            typeUnicode(text)
            if case .changed = await outcome(element, in: app, from: before, within: 0.5) { return .insertedBy("typing") }
        }
        copyOnly(text)
        return .copied("the paste didn't arrive in the field")
    }

    /// The focused element in `app` (nil when there's none or it can't be read).
    static func focusedElement(in app: NSRunningApplication?) -> AXUIElement? {
        guard isTrusted, let app else { return nil }
        var value: CFTypeRef?
        let appElement = AXUIElementCreateApplication(app.processIdentifier)
        AXUIElementSetMessagingTimeout(appElement, 0.25)  // a hung or sleeping app must not stall delivery
        guard AXUIElementCopyAttributeValue(appElement, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        let element = value as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.25)
        return element
    }

    /// The field's text before the cursor and how many characters are selected (nil when it can't be read).
    static func textBeforeCursor(_ element: AXUIElement) -> (before: String, selected: Int)? {
        guard let text = value(of: element) else { return nil }
        var raw: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &raw) == .success,
              let raw, CFGetTypeID(raw) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        guard AXValueGetValue(raw as! AXValue, .cfRange, &range) else { return nil }
        let utf16 = Array(text.utf16)
        guard range.location >= 0, range.location <= utf16.count else { return nil }
        return (String(decoding: utf16[..<range.location], as: UTF16.self), range.length)
    }

    static func value(of element: AXUIElement) -> String? {
        var v: CFTypeRef?
        return AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &v) == .success ? v as? String : nil
    }

    enum FieldOutcome { case changed, unchanged, unknown }

    /// Checks every 50 ms for `seconds`, always against the field that has focus now: `.changed` once its text
    /// differs from `before`; `.unknown` when it can't be read or focus moved to another element (the app rebuilt
    /// the field); `.unchanged` only if the same field still holds exactly `before`.
    static func outcome(_ element: AXUIElement, in app: NSRunningApplication?, from before: String, within seconds: Double) async -> FieldOutcome {
        let deadline = Date().addingTimeInterval(seconds)
        repeat {
            guard let now = focusedElement(in: app), CFEqual(now, element) else { return .unknown }
            guard let text = value(of: now) else { return .unknown }
            if text != before { return .changed }
            if seconds == 0 { return .unchanged }
            try? await Task.sleep(nanoseconds: 50_000_000)
        } while Date() < deadline
        return .unchanged
    }

    /// Whether the field's text differs from `before` at some point within `seconds` (checked every 50 ms).
    static func changes(_ element: AXUIElement, from before: String, within seconds: Double) async -> Bool {
        let deadline = Date().addingTimeInterval(seconds)
        repeat {
            if let now = value(of: element), now != before { return true }
            if seconds == 0 { return false }
            try? await Task.sleep(nanoseconds: 50_000_000)
        } while Date() < deadline
        return false
    }

    /// Types `text` as Unicode key events, a few characters at a time: the fallback for fields that ignore ⌘V.
    static func typeUnicode(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        let units = Array(text.utf16)
        var i = 0
        while i < units.count {
            let chunk = Array(units[i..<min(i + 16, units.count)])
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down)
                chunk.withUnsafeBufferPointer { event?.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: $0.baseAddress) }
                event?.post(tap: .cghidEventTap)
            }
            usleep(4000)
            i += 16
        }
    }

    /// ⌘Z in the front app, for "scratch that" (the key that types "z" in the current layout).
    public static func sendUndo() {
        guard isTrusted else { return }
        let source = CGEventSource(stateID: .combinedSessionState)
        let key = CGKeyCode(keyCode(for: "z", fallback: kVK_ANSI_Z))
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    /// What has keyboard focus in `app`: `editable` is true for a text field, false for something that can't take
    /// text (a button, a list, the window itself, nothing at all), nil when the app doesn't say.
    public static func focusedField(in app: NSRunningApplication?) -> (editable: Bool?, role: String) {
        guard isTrusted, let app else { return (nil, "unknown") }
        let appElement = AXUIElementCreateApplication(app.processIdentifier)
        AXUIElementSetMessagingTimeout(appElement, 0.25)  // a hung or sleeping app must not stall delivery
        // Chrome and Electron apps (Claude, Slack, VS Code) only build their accessibility tree when asked.
        AXUIElementSetAttributeValue(appElement, "AXManualAccessibility" as CFString, kCFBooleanTrue)
        AXUIElementSetAttributeValue(appElement, "AXEnhancedUserInterface" as CFString, kCFBooleanTrue)
        var value: CFTypeRef?
        let err = AXUIElementCopyAttributeValue(appElement, kAXFocusedUIElementAttribute as CFString, &value)
        if err == .noValue {
            // Chrome can report no focused element even with a page open; only trust "nothing" when there's no window either.
            var window: CFTypeRef?
            let hasWindow = AXUIElementCopyAttributeValue(appElement, kAXFocusedWindowAttribute as CFString, &window) == .success
            return hasWindow ? (nil, "window without a focused element") : (false, "no window")
        }
        guard err == .success, let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return (nil, "unknown (\(err.rawValue))") }
        let element = value as! AXUIElement
        func string(_ attr: String) -> String? {
            var v: CFTypeRef?
            return AXUIElementCopyAttributeValue(element, attr as CFString, &v) == .success ? v as? String : nil
        }
        let role = string(kAXRoleAttribute) ?? "?"
        if ["AXTextField", "AXTextArea", "AXComboBox", "AXSearchField"].contains(role) { return (true, role) }
        var settable: DarwinBoolean = false
        if AXUIElementIsAttributeSettable(element, kAXSelectedTextRangeAttribute as CFString, &settable) == .success, settable.boolValue {
            return (true, role)
        }
        var editable: CFTypeRef?
        if AXUIElementCopyAttributeValue(element, "AXEditable" as CFString, &editable) == .success, (editable as? Bool) == true {
            return (true, role)
        }
        // Terminals and some custom editors take typing without looking like text fields.
        if ["AXScrollArea", "AXGroup", "AXUnknown", "AXWebArea"].contains(role) { return (nil, role) }
        return (false, role)
    }

    private static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let key = CGKeyCode(keyCode(for: "v", fallback: kVK_ANSI_V))
        let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// The key that types `letter` in the current layout (Dvorak, AZERTY...), falling back to the US position.
    private static func keyCode(for letter: Character, fallback: Int) -> Int {
        let kVK_ANSI_V = fallback
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return kVK_ANSI_V }
        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
        return data.withUnsafeBytes { bytes -> Int in
            guard let layout = bytes.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return kVK_ANSI_V }
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(
                    layout, UInt16(code), UInt16(kUCKeyActionDown), 0, UInt32(LMGetKbdType()),
                    OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeys, chars.count, &length, &chars)
                if status == noErr, length == 1, chars[0] == UniChar(letter.asciiValue ?? 0) { return code }
            }
            return kVK_ANSI_V
        }
    }
}
